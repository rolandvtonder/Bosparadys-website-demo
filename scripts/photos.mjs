/*
  Builds the site's photos from the originals in ../media.

    npm run photos

  photos.json maps a photo id (p + its number in the media folder) to the
  original file. Each id becomes two WebP files in public/photos:

    <id>.webp      up to 1800px on the long edge, for full-screen and lightbox use
    <id>-sm.webp   640px wide, for cards and grid tiles

  and src/photos.gen.ts records their real sizes, so every <img> can carry
  width/height (no layout shift) and an accurate srcset.

  The originals are never modified. Add a photo by adding a line to
  photos.json and running the script again.
*/

import { readFile, writeFile, mkdir, readdir, rm } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const media = join(root, '..', 'media')
const out = join(root, 'public', 'photos')
const manifest = JSON.parse(await readFile(join(root, 'photos.json'), 'utf8'))

await mkdir(out, { recursive: true })
/* Clear anything not produced from the current manifest. */
for (const f of await readdir(out)) await rm(join(out, f))

const sizes = {}
for (const [id, file] of Object.entries(manifest)) {
  const src = sharp(join(media, file)).rotate()
  const big = await src.clone().resize({ width: 1800, height: 1800, fit: 'inside', withoutEnlargement: true }).webp({ quality: 70 }).toFile(join(out, `${id}.webp`))
  const sm = await src.clone().resize({ width: 640, withoutEnlargement: true }).webp({ quality: 62 }).toFile(join(out, `${id}-sm.webp`))
  sizes[id] = { w: big.width, h: big.height, sw: sm.width }
  process.stdout.write('.')
}

const body = Object.entries(sizes)
  .map(([id, s]) => `  ${id}: { w: ${s.w}, h: ${s.h}, sw: ${s.sw} },`)
  .join('\n')
await writeFile(
  join(root, 'src', 'photos.gen.ts'),
  `/* Generated by scripts/photos.mjs. Do not edit; run \`npm run photos\`. */\n\nexport const PHOTOS = {\n${body}\n} as const\n\nexport type PhotoId = keyof typeof PHOTOS\n`,
)
console.log(`\n${Object.keys(sizes).length} photos written to public/photos`)
